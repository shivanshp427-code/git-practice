package Basics_1;

public class relational_operators {
    public static void main(String[] args) {
        System.out.println(9 > 8);
        System.out.println(9 < 8);
        System.out.println(7 <= 4);
        System.out.println(9 >= 5);
        System.out.println(9 != 9);
        System.out.println(8 == 8);


    }
}
