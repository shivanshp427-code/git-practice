package Basics_1;

public class increment_decrement {
   public static void main(String[] args) {
       int x = 10;
       System.out.println(x);
       x += 6;
       System.out.println(x);
       x *= 4;
       System.out.println(x);
       x -= 10;
       System.out.println(x);
       x /= 27;
       System.out.println(x);
    }
}
